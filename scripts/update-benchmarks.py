"""Import published decode reports from a pinned megakernels revision."""
import concurrent.futures
import json
from pathlib import Path
import re
import sys
import urllib.request

revision = sys.argv[1] if len(sys.argv) > 1 else '4f5f3b77d8af3c140ab9c0c7ffc60776f753185e'
if not re.fullmatch(r'[0-9a-f]{40}', revision):
    raise SystemExit('Pass a full 40-character repository commit SHA.')
base = f'https://raw.githubusercontent.com/megabake/megakernels/{revision}'
readme = urllib.request.urlopen(f'{base}/README.md', timeout=30).read().decode()
packages = []
for line in readme.splitlines():
    if not line.startswith('| [') or '/decode)' not in line:
        continue
    model = re.search(r'^\| \[([^\]]+)\]', line).group(1)
    package = re.search(r'\(kernels/([^/]+)/([^/]+)/decode\)', line)
    packages.append((model, package.group(1), package.group(2)))
if not packages:
    raise SystemExit('No published decode packages found; existing data left unchanged.')

def fetch(package):
    model, package_id, gpu = package
    url = f'{base}/kernels/{package_id}/{gpu}/decode/report.json'
    report = json.load(urllib.request.urlopen(url, timeout=30))
    assert report['model'].split('@')[0] == model
    assert report['decode']['capacity'] == 128
    assert report['samples'] == 40
    assert gpu == 'nvidia-h200-mig-3g-71gb'
    assert report['decode']['megabake_graphed']['launch_count'] == 1
    candidates = [v for k, v in report['decode'].items()
                  if k in ('inductor_graphed', 'inductor_cudagraphs')]
    assert candidates
    for variant in candidates + [report['decode']['megabake_graphed']]:
        assert variant['complete_call_us'] > 0
        assert variant['pipelined_call_us'] > 0
    return {'id': package_id, 'gpu': gpu, 'report': report}

with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
    records = list(pool.map(fetch, packages))
output = {'revision': revision, 'records': records}
root = Path(__file__).resolve().parents[1]
(root / 'js/benchmark-data.js').write_text(
    '// Generated by scripts/update-benchmarks.py from pinned published reports.\n'
    + 'const BENCHMARK_DATA = ' + json.dumps(output, indent=2) + ';\n')
for item in records:
    report = item['report']
    variants = report['decode']
    chosen = min((v for k,v in variants.items() if k in ('inductor_graphed', 'inductor_cudagraphs')),key=lambda v:v['complete_call_us'])
    print(report['model'].split('@')[0], round(variants['megabake_graphed']['complete_call_us']), round(chosen['complete_call_us']), report['published']['measured_at'])
